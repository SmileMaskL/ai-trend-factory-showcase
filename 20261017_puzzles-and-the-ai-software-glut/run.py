#!/usr/bin/env python3
"""
PyPI AI 소프트웨어 글루트 레이더
--------------------------------
오늘의 트렌드 "Puzzles and the AI Software Glut"(HN)에서 출발한 프로젝트.
AI 코드생성 도구가 늘면서 패키지 저장소에 "거의 내용 없는" 패키지가 대량으로
쏟아지는 흐름을, PyPI의 공개 신규 패키지 피드에서 매일 수치로 포착해
텔레그램으로 알려주는 1회성 무인 스크립트.

- 데이터 소스: PyPI 공식 RSS(신규 패키지 피드) + PyPI JSON API (전부 인증 불필요, 무료)
- 의존성: 표준 라이브러리 + requests
- 실행 모델: 한 번 실행 -> 신규 패키지 수집 -> 글루트 신호(저자별 대량 퍼블리시 +
  보일러플레이트 설명) 계산 -> 텔레그램 알림 -> 종료 (서버/데몬 아님)
"""

import html
import json
import os
import sys
import time
from collections import defaultdict
from datetime import datetime, timezone
from pathlib import Path
from xml.etree import ElementTree as ET

import requests

BASE_DIR = Path(__file__).resolve().parent
DATA_DIR = BASE_DIR / "data"
SEEN_FILE = DATA_DIR / "seen_packages.json"
CONFIG_FILE = BASE_DIR / "watchlist.json"

PYPI_NEW_PACKAGES_RSS = "https://pypi.org/rss/packages.xml"
PYPI_JSON_API = "https://pypi.org/pypi/{name}/json"
TELEGRAM_API = "https://api.telegram.org/bot{token}/sendMessage"

HTTP_TIMEOUT = 15
USER_AGENT = "ai-trend-factory-pypi-glut-radar/1.0 (daily batch script; no auth)"
REQUEST_DELAY_SEC = 0.3
MAX_PACKAGES_PER_RUN = 60
MAX_SEEN = 3000


def log(msg):
    print(f"[{datetime.now(timezone.utc).isoformat()}] {msg}")


def load_json(path, default):
    if not path.exists():
        return default
    try:
        with path.open("r", encoding="utf-8") as f:
            return json.load(f)
    except (json.JSONDecodeError, OSError) as e:
        log(f"{path.name} 로드 실패, 기본값 사용: {e}")
        return default


def save_json(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)


def load_config():
    default = {
        "trivial_phrases": [
            "", "todo", "no description", "n/a", "na", "description",
            "my project", "my new package", "a new project", "new project",
            "new package", "test", "test package", "placeholder",
            "sample package", "package description", "generated by",
            "boilerplate", "lorem ipsum", "my awesome project",
            "this is a package", "a simple package", "simple package",
            "awesome package", "default description", "update the summary",
            "todo: description of package",
        ],
        "trivial_min_length": 12,
        "mass_publish_threshold": 3,
    }
    cfg = load_json(CONFIG_FILE, default)
    cfg.setdefault("trivial_phrases", default["trivial_phrases"])
    cfg.setdefault("trivial_min_length", default["trivial_min_length"])
    cfg.setdefault("mass_publish_threshold", default["mass_publish_threshold"])
    return cfg


def fetch_new_packages():
    headers = {"User-Agent": USER_AGENT}
    try:
        resp = requests.get(PYPI_NEW_PACKAGES_RSS, headers=headers, timeout=HTTP_TIMEOUT)
        resp.raise_for_status()
    except requests.RequestException as e:
        log(f"[error] PyPI RSS 수집 실패: {e}")
        return []

    try:
        root = ET.fromstring(resp.content)
    except ET.ParseError as e:
        log(f"[error] PyPI RSS 파싱 실패: {e}")
        return []

    items = []
    for item in root.findall(".//item"):
        title = (item.findtext("title") or "").strip()
        link = (item.findtext("link") or "").strip()
        desc = (item.findtext("description") or "").strip()
        if not title:
            continue
        name = title.split()[0]
        items.append({"name": name, "link": link, "rss_description": desc})
    return items


def fetch_package_info(name):
    headers = {"User-Agent": USER_AGENT}
    try:
        resp = requests.get(PYPI_JSON_API.format(name=name), headers=headers, timeout=HTTP_TIMEOUT)
        if resp.status_code != 200:
            return None
        info = resp.json().get("info", {})
        return {
            "author": (info.get("author") or "").strip(),
            "maintainer": (info.get("maintainer") or "").strip(),
            "summary": (info.get("summary") or "").strip(),
        }
    except (requests.RequestException, ValueError) as e:
        log(f"[warn] {name} JSON API 조회 실패: {e}")
        return None


def is_trivial(summary, trivial_phrases, min_len):
    text = (summary or "").strip().lower()
    if len(text) < min_len:
        return True
    return text in trivial_phrases


def send_telegram(token, chat_id, text):
    url = TELEGRAM_API.format(token=token)
    payload = {
        "chat_id": chat_id,
        "text": text,
        "parse_mode": "HTML",
        "disable_web_page_preview": True,
    }
    try:
        resp = requests.post(url, data=payload, timeout=HTTP_TIMEOUT)
    except requests.RequestException as e:
        log(f"[error] Telegram 요청 예외: {e}")
        return False
    if resp.status_code != 200:
        log(f"[error] Telegram send failed: {resp.status_code} {resp.text}")
        return False
    return True


def main():
    token = os.environ.get("TELEGRAM_BOT_TOKEN")
    chat_id = os.environ.get("TELEGRAM_CHAT_ID")
    if not token or not chat_id:
        log("[error] TELEGRAM_BOT_TOKEN / TELEGRAM_CHAT_ID 환경변수가 필요합니다.")
        sys.exit(1)

    cfg = load_config()
    trivial_phrases = set(p.lower() for p in cfg["trivial_phrases"])
    min_len = cfg["trivial_min_length"]
    mass_threshold = cfg["mass_publish_threshold"]

    seen = set(load_json(SEEN_FILE, []))

    raw_items = fetch_new_packages()
    log(f"PyPI 신규 패키지 피드에서 {len(raw_items)}건 수집")

    new_items = [it for it in raw_items if it["name"] not in seen][:MAX_PACKAGES_PER_RUN]

    if not new_items:
        log("[info] 새로운 패키지 없음. 종료.")
        return

    analyzed = []
    for it in new_items:
        info = fetch_package_info(it["name"])
        time.sleep(REQUEST_DELAY_SEC)
        summary = (info or {}).get("summary") or it["rss_description"]
        author = (info or {}).get("author") or (info or {}).get("maintainer") or ""
        trivial = is_trivial(summary, trivial_phrases, min_len)
        analyzed.append({
            "name": it["name"],
            "summary": summary,
            "author": author,
            "trivial": trivial,
        })

    total = len(analyzed)
    trivial_count = sum(1 for a in analyzed if a["trivial"])
    glut_index = round(trivial_count / total * 100, 1) if total else 0.0

    by_author = defaultdict(list)
    for a in analyzed:
        if a["author"]:
            by_author[a["author"]].append(a)

    mass_publishers = {
        author: pkgs for author, pkgs in by_author.items()
        if len(pkgs) >= mass_threshold
    }

    lines = [
        "🧩 <b>AI 소프트웨어 글루트 레이더</b> (PyPI)",
        "오늘의 트렌드: <i>Puzzles and the AI Software Glut</i> (HN)",
        f"신규 패키지 {total}건 분석 | 보일러플레이트 설명 비율(글루트 지수): "
        f"<b>{glut_index}%</b> ({trivial_count}/{total})",
    ]

    if mass_publishers:
        lines.append("")
        lines.append(f"⚠️ 동일 저자 대량 퍼블리시 감지 ({len(mass_publishers)}명):")
        sorted_pub = sorted(mass_publishers.items(), key=lambda kv: len(kv[1]), reverse=True)[:8]
        for author, pkgs in sorted_pub:
            trivial_in_group = sum(1 for p in pkgs if p["trivial"])
            sample_names = ", ".join(html.escape(p["name"]) for p in pkgs[:5])
            lines.append(
                f"  - {html.escape(author)}: {len(pkgs)}건 "
                f"(보일러플레이트 {trivial_in_group}건) -> {sample_names}"
            )
    else:
        lines.append("")
        lines.append("오늘은 저자별 대량 퍼블리시 신호 없음.")

    trivial_samples = [a for a in analyzed if a["trivial"]][:5]
    if trivial_samples:
        lines.append("")
        lines.append("예시(보일러플레이트/빈 설명):")
        for a in trivial_samples:
            shown = html.escape((a["summary"] or "(설명 없음)")[:60])
            lines.append(f"  - {html.escape(a['name'])}: \"{shown}\"")

    message = "\n".join(lines)

    ok = send_telegram(token, chat_id, message)
    if ok:
        seen.update(a["name"] for a in analyzed)
        save_json(SEEN_FILE, list(seen)[-MAX_SEEN:])
        log(f"[info] 텔레그램 전송 완료. {total}건 처리.")
    else:
        log("[error] 텔레그램 전송 실패. seen 갱신 안 함(다음 실행에서 재시도).")


if __name__ == "__main__":
    main()